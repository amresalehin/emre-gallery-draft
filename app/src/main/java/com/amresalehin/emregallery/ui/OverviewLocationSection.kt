import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextOverflow
import androidx.compose.ui.unit.dp

@Composable
internal fun OverviewLocationSection(
    hasLocation: Boolean,
    primaryLocation: String,
    secondaryLocation: String,
    onOpenMap: () -> Unit,
    onEditLocation: () -> Unit
) {
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        OverviewSectionHeader(
            title = "Location",
            actionIcon = if (hasLocation) Icons.Default.Edit else null,
            actionContentDescription = if (hasLocation) "Edit location" else null,
            onActionClick = if (hasLocation) onEditLocation else null
        )

        if (hasLocation) {
            DetailCard(onClick = onOpenMap) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Box(
                        modifier = Modifier
                            .size(44.dp)
                            .clip(RoundedCornerShape(10.dp))
                            .background(MaterialTheme.colorScheme.surfaceContainerHigh),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.LocationOn,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.onSurface,
                            modifier = Modifier.size(20.dp)
                        )
                    }
                    Spacer(Modifier.width(12.dp))
                    Column(modifier = Modifier.weight(1f)) {
                        Text(
                            text = primaryLocation,
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onSurface,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                        if (secondaryLocation.isNotBlank()) {
                            Spacer(Modifier.height(2.dp))
                            Text(
                                text = secondaryLocation,
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                maxLines = 1,
                                overflow = TextOverflow.Ellipsis
                            )
                        }
                    }
                }
            }
        } else {
            OverviewAddEmptyPill(
                label = "Add location",
                icon = Icons.Default.AddLocationAlt,
                onClick = onEditLocation
            )
        }
    }
}
